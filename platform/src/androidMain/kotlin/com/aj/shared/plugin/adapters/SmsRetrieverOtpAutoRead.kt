package com.aj.shared.plugin.adapters

import android.app.Activity
import android.content.BroadcastReceiver
import android.content.Context
import android.content.Intent
import android.content.IntentFilter
import android.os.Build
import com.aj.shared.plugin.OtpAutoReadListener
import com.aj.shared.plugin.OtpAutoReadService
import com.aj.shared.plugin.ServiceCapability
import com.google.android.gms.auth.api.phone.SmsRetriever
import com.google.android.gms.common.api.CommonStatusCodes
import com.google.android.gms.common.api.Status

/**
 * Android SMS Retriever OTP auto-read (no SMS permission required).
 *
 * ```kotlin
 * EazyCmp.install { otpAutoRead = SmsRetrieverOtpAutoRead(activity) }
 * ```
 *
 * SMS body must include the app hash generated by AppSignatureHelper / Play SMS Retriever rules.
 */
class SmsRetrieverOtpAutoRead(
    private val activity: Activity,
    private val otpRegex: Regex = Regex("""\b(\d{4,8})\b"""),
) : OtpAutoReadService {

    private var listener: OtpAutoReadListener? = null
    private var receiver: BroadcastReceiver? = null

    override val isAvailable: Boolean = true
    override val capability: ServiceCapability = ServiceCapability.FULL
    override val hostHint: String? = null

    override fun startListening(listener: OtpAutoReadListener) {
        stopListening()
        this.listener = listener
        SmsRetriever.getClient(activity).startSmsRetriever()
            .addOnFailureListener { error ->
                listener.onError(error.message ?: "Failed to start SMS Retriever")
            }

        val broadcast = object : BroadcastReceiver() {
            override fun onReceive(context: Context?, intent: Intent?) {
                if (intent?.action != SmsRetriever.SMS_RETRIEVED_ACTION) return
                val extras = intent.extras ?: return
                val status = extras.get(SmsRetriever.EXTRA_STATUS) as? Status ?: return
                when (status.statusCode) {
                    CommonStatusCodes.SUCCESS -> {
                        val message = extras.getString(SmsRetriever.EXTRA_SMS_MESSAGE).orEmpty()
                        val otp = otpRegex.find(message)?.groupValues?.getOrNull(1)
                        if (otp.isNullOrBlank()) {
                            listener.onError("OTP not found in SMS")
                        } else {
                            listener.onOtpReceived(otp)
                        }
                        stopListening()
                    }
                    CommonStatusCodes.TIMEOUT -> {
                        listener.onError("SMS Retriever timed out")
                        stopListening()
                    }
                }
            }
        }
        receiver = broadcast
        val filter = IntentFilter(SmsRetriever.SMS_RETRIEVED_ACTION)
        if (Build.VERSION.SDK_INT >= 33) {
            activity.registerReceiver(broadcast, filter, Context.RECEIVER_EXPORTED)
        } else {
            @Suppress("UnspecifiedRegisterReceiverFlag")
            activity.registerReceiver(broadcast, filter)
        }
    }

    override fun stopListening() {
        receiver?.let {
            try {
                activity.unregisterReceiver(it)
            } catch (_: Throwable) {
            }
        }
        receiver = null
        listener = null
    }
}
